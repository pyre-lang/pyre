//! End-to-end coverage for the native `_cffi_backend` module, run through the
//! same startup shape as the `pyrex` launcher.
//!
//! The programs are transcribed from `extra_tests/cffi_tests/test_c.py`, whose
//! upstream is `pypy/module/_cffi_backend/test/_backend_test_c.py`.  Only the
//! part of that file the module answers today is covered: primitives, `void`,
//! pointers, arrays, structs, unions, enums, function types, libraries,
//! handles, allocators, buffers, saved errno, wide characters and M3's
//! remaining module functions.
//! An uncaught `assert` in a program surfaces here as a failing test, so a
//! passing test means every read-back assertion held.
//!
//! `_backend_test_c.py` calls into a C library built for the test suite; the
//! programs here call libc instead, through the handle `dlopen(NULL)` gives.

use std::rc::Rc;

use pyre_interpreter::call::{register_build_class, set_last_exec_ctx};
use pyre_interpreter::importing;
use pyre_interpreter::pyframe::PyFrame;
use pyre_interpreter::{Mode, PyExecutionContext, compile_source_with_filename};
use pyre_jit::eval::{eval_with_jit, init_jit_hooks};

fn run_harness(program: &str, name: &str) -> Result<(), String> {
    // Same startup as `pyrex::real_main`, on this process's own GC.
    pyre_interpreter::stack_check::set_recursion_limit(5000)
        .map_err(|_| "set_recursion_limit failed".to_string())?;
    pyre_module::register();
    init_jit_hooks();

    let cwd = std::env::current_dir().map_err(|e| e.to_string())?;
    importing::init_sys_path(&cwd, Some(cwd.as_os_str()));
    importing::add_sys_path_0();
    importing::set_sys_argv(&[std::ffi::OsString::from(name)]);

    let code = compile_source_with_filename(program, Mode::Exec, name)
        .map_err(|e| format!("compile error: {e}"))?;

    register_build_class();

    let execution_context = Rc::new(PyExecutionContext::default());
    set_last_exec_ctx(Rc::as_ptr(&execution_context));

    let mut frame = PyFrame::new_with_context(code, execution_context)
        .map_err(|e| format!("frame setup error: {}", e.message_text()))?;

    let canonical = frame.get_w_globals();
    let main_module =
        pyre_object::w_module_new_aliasing_dict(pyre_object::w_str_new("__main__"), canonical);
    importing::set_sys_module("__main__", main_module);

    // An `AssertionError` a program raises is object-backed, so its `message`
    // field is empty and only `message_text` derives the text from
    // `exc_object`.
    eval_with_jit(&mut frame, None)
        .map_err(|e| format!("execution error: {}", e.message_text()))?;
    Ok(())
}

/// Run one test in its own process, then `run_harness` on a 256 MiB worker.
///
/// Unless `PYRE_CFFI_BACKEND_CHILD` is set, re-exec this binary with `--exact`
/// for the libtest thread name, `--nocapture`, and `--test-threads=1`. The
/// child has the variable set and runs `run_harness` on the worker thread.
/// The child builds one GC through the same startup as `pyrex::real_main`.
fn run_on_worker(program: &'static str, name: &'static str) {
    const CHILD: &str = "PYRE_CFFI_BACKEND_CHILD";
    if std::env::var_os(CHILD).is_none() {
        let current = std::thread::current();
        let test_name = current.name();
        assert!(test_name.is_some(), "libtest names the test thread");
        let test_name = test_name.unwrap();
        let output = std::process::Command::new(std::env::current_exe().unwrap())
            .args(["--exact", test_name, "--nocapture", "--test-threads=1"])
            .env(CHILD, "1")
            .output()
            .expect("re-exec cffi_backend test in its own process");
        assert!(
            output.status.success(),
            "{name}\n{}\n{}",
            String::from_utf8_lossy(&output.stdout),
            String::from_utf8_lossy(&output.stderr),
        );
        return;
    }
    let handle = std::thread::Builder::new()
        .stack_size(256 * 1024 * 1024)
        .spawn(move || run_harness(program, name))
        .expect("spawn worker thread");
    handle.join().expect("worker thread panicked").expect(name);
}

