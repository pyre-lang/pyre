//! Generate the wasm-runner's diagnostic label arrays and fbw ring layout
//! from the authority sources. The runner is a wasmtime host and cannot
//! import `majit-metainterp` / `pyre-jit-trace` / `pyre-jit`, so it used to
//! restate those arrays by hand; a short copy dropped the tail and a rename
//! mis-keyed every later tally into check.py's flat map. Rebuilds pick up
//! an appended slot; a broken extract panics here instead of shipping a
//! silent subset.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

fn main() {
    println!("cargo:rerun-if-changed=build.rs");

    let root = repo_root();
    let authorities: &[(&str, &str)] = &[
        ("majit/majit-metainterp/src/lib.rs", "MC_DIAG_LABELS"),
        (
            "majit/majit-metainterp/src/jitprof.rs",
            "ABORT_COUNTER_KINDS",
        ),
        ("majit/majit-backend-wasm/src/lib.rs", "BRIDGE_DIAG_LABELS"),
        ("pyre/pyre-jit/src/eval.rs", "PORTAL_DIAG_LABELS"),
        ("pyre/pyre-jit-trace/src/trace.rs", "fbw_diag"),
    ];
    for (rel, _) in authorities {
        let path = root.join(rel);
        println!("cargo:rerun-if-changed={}", path.display());
    }

    let mc_src = read(&root.join("majit/majit-metainterp/src/lib.rs"));
    let abort_src = read(&root.join("majit/majit-metainterp/src/jitprof.rs"));
    let bridge_src = read(&root.join("majit/majit-backend-wasm/src/lib.rs"));
    let portal_src = read(&root.join("pyre/pyre-jit/src/eval.rs"));
    let fbw_src = read(&root.join("pyre/pyre-jit-trace/src/trace.rs"));

    let abort = expect_array(
        &abort_src,
        "pub const ABORT_COUNTER_KINDS",
        "ABORT_COUNTER_KINDS",
        6,
        "too_long",
    );
    let bridge = expect_array(
        &bridge_src,
        "pub const BRIDGE_DIAG_LABELS",
        "BRIDGE_DIAG_LABELS",
        50,
        "entered",
    );
    let portal = expect_array(
        &portal_src,
        "pub const PORTAL_DIAG_LABELS",
        "PORTAL_DIAG_LABELS",
        2,
        "can_enter_jit",
    );
    let mc = expect_array(
        &mc_src,
        "pub const MC_DIAG_LABELS",
        "MC_DIAG_LABELS",
        80,
        "mc_entered",
    );
    let fbw = expect_array(
        &fbw_src,
        "pub const LABELS",
        "fbw_diag::LABELS",
        18,
        "fbw_walks",
    );

    let ring_entries = declared_int(&fbw_src, "pub const RING_ENTRIES: usize = ", "RING_ENTRIES");
    let ring_stride = declared_int(&fbw_src, "pub const RING_STRIDE: usize = ", "RING_STRIDE");
    let name_slots = declared_int(&fbw_src, "pub const NAME_SLOTS: usize = ", "NAME_SLOTS");
    let shift_effects = declared_expr(&fbw_src, "pub const SHIFT_EFFECTS: u32 = ", "SHIFT_EFFECTS");
    let shift_journal = declared_expr(&fbw_src, "pub const SHIFT_JOURNAL: u32 = ", "SHIFT_JOURNAL");
    let shift_exec_mf = declared_expr(&fbw_src, "pub const SHIFT_EXEC_MF: u32 = ", "SHIFT_EXEC_MF");
    let shift_leg = declared_expr(&fbw_src, "pub const SHIFT_LEG: u32 = ", "SHIFT_LEG");
    let field_mask = declared_expr(&fbw_src, "pub const FIELD_MASK: u64 = ", "FIELD_MASK");
    assert!(
        ring_entries >= 1 && ring_stride >= 1 && name_slots >= 1,
        "fbw ring geometry collapsed: RING_ENTRIES={ring_entries} \
         RING_STRIDE={ring_stride} NAME_SLOTS={name_slots}"
    );

    let valid = declared_bitflag_expr(&fbw_src, "RingFlags", "VALID");
    let committed = declared_bitflag_expr(&fbw_src, "RingFlags", "COMMITTED");
    let bridge_flag = declared_bitflag_expr(&fbw_src, "RingFlags", "BRIDGE");

    let mut out = String::new();
    out.push_str(
        "// @generated by pyre-wasm-runner/build.rs from the authority arrays. Do not edit.\n\n",
    );
    emit_str_array(&mut out, "ABORT_DIAG_LABELS", &abort);
    emit_str_array(&mut out, "BRIDGE_DIAG_LABELS", &bridge);
    emit_str_array(&mut out, "PORTAL_DIAG_LABELS", &portal);
    emit_str_array(&mut out, "MC_DIAG_LABELS", &mc);
    emit_str_array(&mut out, "FBW_DIAG_LABELS", &fbw);

    writeln!(
        out,
        "const RING_BASE: u32 = FBW_DIAG_LABELS.len() as u32;\n\
         const RING_ENTRIES: u32 = {ring_entries};\n\
         const RING_STRIDE: u32 = {ring_stride};\n\
         const NAME_SLOTS: u32 = {name_slots};\n\
         const SHIFT_EFFECTS: u32 = {shift_effects};\n\
         const SHIFT_JOURNAL: u32 = {shift_journal};\n\
         const SHIFT_EXEC_MF: u32 = {shift_exec_mf};\n\
         const SHIFT_LEG: u32 = {shift_leg};\n\
         const FIELD_MASK: u64 = {field_mask};\n"
    )
    .unwrap();

    writeln!(
        out,
        "bitflags::bitflags! {{\n\
         \x20   /// Generated from `pyre_jit_trace::trace::fbw_diag::RingFlags`.\n\
         \x20   #[repr(transparent)]\n\
         \x20   #[derive(Clone, Copy, PartialEq, Eq, Debug)]\n\
         \x20   struct FbwRingFlags: u64 {{\n\
         \x20       const VALID = {valid};\n\
         \x20       const COMMITTED = {committed};\n\
         \x20       const BRIDGE = {bridge_flag};\n\
         \x20   }}\n\
         }}"
    )
    .unwrap();

    let dest = Path::new(&std::env::var("OUT_DIR").expect("OUT_DIR")).join("diag_mirrors.rs");
    std::fs::write(&dest, out).unwrap_or_else(|err| panic!("write {}: {err}", dest.display()));
}

fn repo_root() -> PathBuf {
    Path::new(&std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"))
        .ancestors()
        .nth(2)
        .expect("CARGO_MANIFEST_DIR has fewer than two ancestors")
        .to_path_buf()
}

fn read(path: &Path) -> String {
    std::fs::read_to_string(path)
        .unwrap_or_else(|err| panic!("cannot read {} — {err}", path.display()))
}

/// String literals of the first array value following `anchor`.
///
/// A declaration can carry a `[` in its TYPE (`&[&str]`, `&[(i32, &str)]`),
/// so this steps to `=` first and then to the `[` that opens the value.
fn array_after(text: &str, anchor: &str, what: &str) -> Vec<String> {
    let at = text
        .find(anchor)
        .unwrap_or_else(|| panic!("{what}: anchor {anchor:?} not found"));
    let eq = text[at..]
        .find('=')
        .unwrap_or_else(|| panic!("{what}: no `=` after anchor {anchor:?}"))
        + at;
    let open = eq
        + text[eq..]
            .find('[')
            .unwrap_or_else(|| panic!("{what}: no `[` after `=` for {anchor:?}"));

    let bytes = text.as_bytes();
    let mut depth = 0usize;
    let mut end = open;
    for (i, b) in bytes.iter().enumerate().skip(open) {
        match b {
            b'[' => depth += 1,
            b']' => {
                depth -= 1;
                if depth == 0 {
                    end = i;
                    break;
                }
            }
            _ => {}
        }
    }
    assert!(depth == 0 && end > open, "{what}: unbalanced array literal");

    let mut out = Vec::new();
    for line in text[open + 1..end].lines() {
        let line = line.trim();
        if line.starts_with("//") {
            continue;
        }
        let mut rest = line;
        while let Some(s) = rest.find('"') {
            let after = &rest[s + 1..];
            let Some(e) = after.find('"') else { break };
            out.push(after[..e].to_string());
            rest = &after[e + 1..];
        }
    }
    out
}

fn expect_array(src: &str, anchor: &str, what: &str, min_len: usize, first: &str) -> Vec<String> {
    let labels = array_after(src, anchor, what);
    assert!(
        labels.len() >= min_len,
        "{what}: extracted {} labels from {anchor:?}, expected at least {min_len} — \
         the parser likely landed on the wrong array",
        labels.len(),
    );
    assert_eq!(
        labels.first().map(String::as_str),
        Some(first),
        "{what}: first label is {:?} not {first:?} — wrong array, or a tally was \
         inserted at the front (append only)",
        labels.first().map(String::as_str),
    );
    labels
}

fn declared_expr(src: &str, anchor: &str, what: &str) -> String {
    let at = src
        .find(anchor)
        .unwrap_or_else(|| panic!("{what}: {anchor:?} declaration not found"));
    let tail = src[at + anchor.len()..].trim_start();
    let expr: String = tail
        .chars()
        .take_while(|c| !matches!(*c, ';' | ',' | '\n' | '}'))
        .collect();
    let expr = expr.trim();
    assert!(
        !expr.is_empty(),
        "{what}: {anchor:?} has an empty expression"
    );
    expr.to_string()
}

fn declared_int(src: &str, anchor: &str, what: &str) -> u64 {
    let expr = declared_expr(src, anchor, what);
    parse_u64_expr(&expr)
        .unwrap_or_else(|| panic!("{what}: {anchor:?} is not a number or `N << M` ({expr:?})"))
}

fn declared_bitflag_expr(src: &str, type_name: &str, flag: &str) -> String {
    let type_at = src
        .find(type_name)
        .unwrap_or_else(|| panic!("bitflags type {type_name:?} not found"));
    declared_expr(
        &src[type_at..],
        &format!("const {flag} = "),
        &format!("{type_name}::{flag}"),
    )
}

fn parse_u64_expr(expr: &str) -> Option<u64> {
    if let Some((left, right)) = expr.split_once("<<") {
        let left = parse_u64_literal(left.trim())?;
        let right = parse_u64_literal(right.trim())?;
        return left.checked_shl(u32::try_from(right).ok()?);
    }
    parse_u64_literal(expr)
}

fn parse_u64_literal(s: &str) -> Option<u64> {
    if let Some(hex) = s.strip_prefix("0x").or_else(|| s.strip_prefix("0X")) {
        u64::from_str_radix(hex, 16).ok()
    } else {
        s.parse().ok()
    }
}

fn emit_str_array(out: &mut String, name: &str, labels: &[String]) {
    writeln!(out, "const {name}: &[&str] = &[").unwrap();
    for label in labels {
        let escaped = label.replace('\\', "\\\\").replace('"', "\\\"");
        writeln!(out, "    \"{escaped}\",").unwrap();
    }
    writeln!(out, "];\n").unwrap();
}
